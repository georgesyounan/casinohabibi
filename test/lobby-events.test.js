import assert from 'node:assert/strict';
import test from 'node:test';
import { DatabaseSync } from 'node:sqlite';
import { createLobbyEvents, weekStart } from '../lib/lobby-events.js';

test('weekly free tickets, private counts and one demo payout survive retries and rollover', t=>{
  const db=new DatabaseSync(':memory:');t.after(()=>db.close());
  db.exec(`CREATE TABLE tenants(id TEXT PRIMARY KEY);
    CREATE TABLE players(id INTEGER PRIMARY KEY,tenant_id TEXT,access_status TEXT,report_fixture INTEGER);
    CREATE TABLE player_safety(player INTEGER,excluded_at INTEGER);
    CREATE TABLE ledger(id INTEGER PRIMARY KEY,tenant_id TEXT,player INTEGER,game TEXT,wager INTEGER,amount INTEGER,request_id TEXT,created_at INTEGER,outcome TEXT,UNIQUE(player,request_id));
    INSERT INTO tenants VALUES('a'),('b');
    INSERT INTO players VALUES(1,'a','active',0),(2,'a','active',0),(3,'b','active',0),(4,'a','active',1);
    INSERT INTO player_safety VALUES(2,1);`);
  const race={rows:[],own:null};
  const events=createLobbyEvents(db,{fail:(_,reason)=>{throw Error(reason);},accountBreaks:{at:()=>null},standings:()=>race});
  const monday=Date.parse('2026-11-16T00:00:00Z'),day=86400000,sunday=monday+6*day,now=sunday+day-1;
  assert.equal(weekStart(now),monday);
  assert.deepEqual(events.enter('a',1,monday,monday),{added:true});
  assert.deepEqual(events.enter('a',1,monday,monday+123),{added:false});
  assert.deepEqual(events.enter('a',1,sunday,now),{added:true});
  for(const id of [2,3,4])assert.throws(()=>events.enter('a',id,sunday,now),/discoveryPaused/);
  assert.throws(()=>events.enter('a',1,sunday,now+1),/clubDayChanged/);
  assert.equal(events.board('a',1,now).raffle.own,2);
  assert.equal(events.board('a',null,now).raffle.own,0);
  assert.equal(events.board('b',3,now).raffle.total,0);
  assert.equal(events.hasDue(now),false);
  assert.equal(events.hasDue(now+1),true);
  events.settle(now+1);events.settle(now+2);
  const after=events.board('a',1,now+3);
  assert.equal(after.start,now+1); assert.equal(after.raffle.own,0);
  assert.equal(after.raffle.previous.won,1);assert.equal(after.raffle.previous.entries,2);
  assert.equal(events.board('a',null,now+3).raffle.previous.won,0);
  assert.equal(db.prepare('SELECT SUM(amount) AS amount FROM ledger').get().amount,after.prize);
  assert.equal(events.hasDue(now+3),false);assert.equal(after.rounds.length,0);
  const bet=db.prepare("INSERT INTO ledger(tenant_id,player,game,wager,amount,created_at) VALUES(?,?,'gold',100,?,?)");
  bet.run('a',1,200,now);bet.run('a',1,-100,now+1);bet.run('a',4,900,now);bet.run('b',3,1500,now);
  const board=events.board('a',null,now+4);
  assert.equal(board.rounds.length,2);assert.equal(board.wins.length,1);
  const {cursor,...win}=board.wins[0];assert.ok(cursor>0);
  assert.deepEqual(win,{game:'gold',wager:100,amount:200,at:now});
  for(let i=0;i<103;i++)bet.run('a',1,100,now+3);
  const first=events.winFeed('a',cursor,now+4),second=events.winFeed('a',first.cursor,now+4),third=events.winFeed('a',second.cursor,now+4);
  assert.deepEqual([first,second,third].map(x=>[x.wins.length,x.more]),[[48,true],[48,true],[7,false]]);
  assert.equal(new Set([...first.wins,...second.wins,...third.wins].map(x=>x.cursor)).size,103);
  assert.equal(events.winFeed('a',third.cursor,now+5).wins.length,0);
  assert.equal(events.winFeed('b',null,now+5).wins[0].amount,1500);
  assert.equal(events.winFeed('a',null,now+day+10).wins.length,0);
  assert.throws(()=>events.winFeed('a',-1,now),/invalid/);
});
